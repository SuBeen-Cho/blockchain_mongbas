#!/usr/bin/env node

'use strict';

const { computeCredentialBoundNullifier } = require('../src/lib/credentialBinding');
const { computeCredentialRevocationHandle } = require('../src/lib/credentialRevocation');

const BASE_URL = (process.env.E2E_BASE_URL || process.env.BASE_URL || 'http://localhost:3000').replace(/\/$/, '');
const ADMIN_API_TOKEN = process.env.ADMIN_API_TOKEN || '';
const ELECTION_ID = process.env.E2E_ELECTION_ID || `revocation-e2e-${Date.now()}`;
const CANDIDATES = ['CANDIDATE_A', 'CANDIDATE_B'];

async function requestJson(path, options = {}) {
  const response = await fetch(`${BASE_URL}${path}`, {
    ...options,
    headers: {
      'content-type': 'application/json',
      ...(ADMIN_API_TOKEN ? { authorization: `Bearer ${ADMIN_API_TOKEN}` } : {}),
      ...(options.headers || {}),
    },
  });
  const text = await response.text();
  let body;
  try { body = text ? JSON.parse(text) : null; } catch { body = { raw: text }; }
  return { status: response.status, ok: response.ok, body };
}

async function expectOk(label, responsePromise) {
  const response = await responsePromise;
  if (!response.ok) throw new Error(`${label}: HTTP ${response.status} ${JSON.stringify(response.body)}`);
  process.stdout.write(`[OK] ${label}\n`);
  return response.body;
}

async function expectRejected(label, responsePromise) {
  const response = await responsePromise;
  if (response.ok) throw new Error(`${label}: unexpectedly succeeded ${JSON.stringify(response.body)}`);
  process.stdout.write(`[OK] ${label}: rejected HTTP ${response.status}\n`);
  return response;
}

async function issueCredential(voterID) {
  const issued = await expectOk(`issue ${voterID}`, requestJson('/api/credential/idemix', {
    method: 'POST',
    body: JSON.stringify({
      enrollmentID: voterID,
      enrollmentSecret: `${voterID}pw`,
      electionID: ELECTION_ID,
    }),
  }));
  if (!issued.credential || !issued.nullifierMaterial) {
    throw new Error(`${voterID} credential response lacks credential/nullifierMaterial`);
  }
  return issued;
}

async function cast(issued, nullifierHash, candidateID) {
  return requestJson('/api/vote', {
    method: 'POST',
    headers: { 'x-idemix-credential': issued.credential },
    body: JSON.stringify({ electionID: ELECTION_ID, candidateID, nullifierHash }),
  });
}

async function main() {
  process.stdout.write(`[INFO] baseUrl=${BASE_URL}\n[INFO] electionID=${ELECTION_ID}\n`);
  await expectOk('API reachable', requestJson('/health'));
  const now = Math.floor(Date.now() / 1000);
  await expectOk('create election', requestJson('/api/elections', {
    method: 'POST',
    body: JSON.stringify({
      electionID: ELECTION_ID,
      title: `Credential revocation E2E ${ELECTION_ID}`,
      description: 'Generated by credential-revocation-e2e.js',
      candidates: CANDIDATES,
      startTime: now - 10,
      endTime: now + 3600,
    }),
  }));
  await expectOk('activate election', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/activate`, {
    method: 'POST', body: '{}',
  }));
  const { blindingFactor } = await expectOk('fetch blinding factor', requestJson(
    `/api/elections/${encodeURIComponent(ELECTION_ID)}/blinding-factor`,
  ));

  const revokedCredential = await issueCredential('voter1');
  const revokedNullifier = computeCredentialBoundNullifier(
    revokedCredential.nullifierMaterial, ELECTION_ID, blindingFactor,
  );
  const revocationHandle = computeCredentialRevocationHandle(
    revokedCredential.nullifierMaterial, ELECTION_ID, blindingFactor,
  );
  const revokePath = `/api/elections/${encodeURIComponent(ELECTION_ID)}/revoke-credential`;
  const revokeBody = { revocationHandle, reasonCode: 'credential-compromised' };
  const firstRevoke = await expectOk('revoke credential', requestJson(revokePath, {
    method: 'POST', body: JSON.stringify(revokeBody),
  }));
  if ('revocationHandle' in firstRevoke) throw new Error('revocation API echoed the sensitive handle');
  await expectOk('idempotent duplicate revocation', requestJson(revokePath, {
    method: 'POST', body: JSON.stringify(revokeBody),
  }));
  await expectRejected('conflicting revocation reason', requestJson(revokePath, {
    method: 'POST',
    body: JSON.stringify({ revocationHandle, reasonCode: 'issued-in-error' }),
  }));
  await expectRejected('revoked credential vote', cast(revokedCredential, revokedNullifier, CANDIDATES[0]));

  const validCredential = await issueCredential('voter2');
  const validNullifier = computeCredentialBoundNullifier(
    validCredential.nullifierMaterial, ELECTION_ID, blindingFactor,
  );
  await expectOk('unrevoked credential vote', cast(validCredential, validNullifier, CANDIDATES[1]));
  const record = await expectOk('read committed nullifier', requestJson(
    `/api/nullifier/${encodeURIComponent(validNullifier)}`,
  ));
  if (record.credentialHash !== undefined && record.credentialHash !== '') {
    throw new Error('new public Nullifier leaked credentialHash');
  }
  if (record.nullifierHash !== validNullifier) throw new Error('committed nullifier mismatch');

  process.stdout.write(JSON.stringify({
    schema: 'mongbas-credential-revocation-e2e/v1',
    electionID: ELECTION_ID,
    revokedRejected: true,
    unrevokedCommitted: true,
    publicCredentialHashAbsent: true,
  }) + '\n');
}

if (require.main === module) {
  main().catch(error => {
    process.stderr.write(`[FAIL] ${error.message}\n`);
    process.exitCode = 1;
  });
}

module.exports = { requestJson };
