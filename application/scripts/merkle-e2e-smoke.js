#!/usr/bin/env node

'use strict';

const crypto = require('crypto');
const { computeCredentialBoundNullifier } = require('../src/lib/credentialBinding');

const BASE_URL = (process.env.E2E_BASE_URL || process.env.BASE_URL || 'http://localhost:3000').replace(/\/$/, '');
const ADMIN_API_TOKEN = process.env.ADMIN_API_TOKEN || '';
const ELECTION_ID = process.env.E2E_ELECTION_ID || `merkle-e2e-${Date.now()}`;
const CANDIDATES = ['CANDIDATE_A', 'CANDIDATE_B'];

function sha256Hex(input) {
  return crypto.createHash('sha256').update(input).digest('hex');
}

async function requestJson(path, options = {}) {
  const res = await fetch(`${BASE_URL}${path}`, {
    ...options,
    headers: {
      'content-type': 'application/json',
      ...(ADMIN_API_TOKEN ? { authorization: `Bearer ${ADMIN_API_TOKEN}` } : {}),
      ...(options.headers || {}),
    },
  });
  const text = await res.text();
  let body = null;
  try { body = text ? JSON.parse(text) : null; } catch { body = { raw: text }; }
  return { status: res.status, ok: res.ok, body };
}

async function assertOk(label, promise) {
  const res = await promise;
  if (!res.ok) throw new Error(`${label} failed: HTTP ${res.status} ${JSON.stringify(res.body)}`);
  console.log(`[OK] ${label}`);
  return res.body;
}

// Merkle root 로컬 재계산 (frontend/src/utils/crypto.js와 동일 로직)
// position = 형제 노드의 위치 (right → 형제가 오른쪽 → current가 왼쪽)
function computeLocalRoot(leafHash, proofPath) {
  if (!proofPath || proofPath.length === 0) return leafHash;
  let current = leafHash;
  for (const step of proofPath) {
    if (step.position === 'right') {
      // 형제가 오른쪽 → current | sibling
      current = sha256Hex(current + step.hash);
    } else {
      // 형제가 왼쪽 → sibling | current
      current = sha256Hex(step.hash + current);
    }
  }
  return current;
}

async function main() {
  console.log(`[INFO] baseUrl=${BASE_URL}`);
  console.log(`[INFO] electionID=${ELECTION_ID}`);

  await assertOk('API root reachable', requestJson('/'));

  // 1. 선거 생성 + 활성화
  const now = Math.floor(Date.now() / 1000);
  await assertOk('create election', requestJson('/api/elections', {
    method: 'POST',
    body: JSON.stringify({
      electionID: ELECTION_ID,
      title: `Merkle E2E ${ELECTION_ID}`,
      description: 'Generated by merkle-e2e-smoke.js',
      candidates: CANDIDATES,
      startTime: now - 10,
      endTime: now + 3600,
    }),
  }));
  await assertOk('activate election', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/activate`, {
    method: 'POST', body: '{}',
  }));

  // 2. blinding factor 조회
  const bf = await assertOk('fetch blinding factor', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/blinding-factor`));

  // 3. credential 발급 + 투표 (2명)
  const voters = [
    { id: 'voter1', candidate: 'CANDIDATE_A' },
    { id: 'voter2', candidate: 'CANDIDATE_B' },
  ];
  const nullifiers = [];

  for (const v of voters) {
    const cred = await assertOk(`issue credential (${v.id})`, requestJson('/api/credential/idemix', {
      method: 'POST',
      body: JSON.stringify({ enrollmentID: v.id, enrollmentSecret: `${v.id}pw`, electionID: ELECTION_ID }),
    }));

    if (typeof cred.nullifierMaterial !== 'string' || cred.nullifierMaterial.length === 0) {
      throw new Error(`credential (${v.id}) has no signed nullifier material`);
    }
    const nullifierHash = computeCredentialBoundNullifier(
      cred.nullifierMaterial, ELECTION_ID, bf.blindingFactor,
    );

    await assertOk(`vote (${v.id} -> ${v.candidate})`, requestJson('/api/vote', {
      method: 'POST',
      headers: { 'x-idemix-credential': cred.credential },
      body: JSON.stringify({ electionID: ELECTION_ID, candidateID: v.candidate, nullifierHash }),
    }));
    nullifiers.push(nullifierHash);
  }

  // 4. 선거 종료
  await assertOk('close election', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/close`, {
    method: 'POST', body: '{}',
  }));

  // 5. Merkle tree 생성
  const merkleResult = await assertOk('build merkle tree', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/merkle`, {
    method: 'POST', body: '{}',
  }));
  console.log(`[INFO] merkle root: ${merkleResult.rootHash}`);
  console.log(`[INFO] merkle leaf count: ${merkleResult.leafCount}`);

  // 6. Merkle root 조회
  const merkleRoot = await assertOk('get merkle root', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/merkle`));
  const chainRoot = merkleRoot.rootHash;
  console.log(`[INFO] chain root: ${chainRoot}`);

  // 7. 각 voter의 proof 조회 + local root 재계산
  for (let i = 0; i < nullifiers.length; i++) {
    const nh = nullifiers[i];
    const proofResp = await assertOk(
      `get proof (voter${i + 1})`,
      requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/proof/${nh}`),
    );

    // proof 응답에 필수 필드 확인
    if (!proofResp.leafHash) throw new Error(`proof for voter${i + 1} has no leafHash`);
    if (!proofResp.candidateCommitment) throw new Error(`proof for voter${i + 1} has no candidateCommitment`);
    if (!proofResp.encryptedCandidateID) throw new Error(`proof for voter${i + 1} has no encryptedCandidateID`);

    // local root 재계산
    const computedRoot = computeLocalRoot(proofResp.leafHash, proofResp.proof);
    if (computedRoot === chainRoot) {
      console.log(`[OK] merkle proof verified (voter${i + 1}): computed root matches chain root`);
    } else {
      throw new Error(`Merkle root mismatch for voter${i + 1}: computed=${computedRoot}, chain=${chainRoot}`);
    }
  }

  // 8. 변조 leafHash로 root 재계산 시 불일치 확인
  const fakeLeafHash = sha256Hex('tampered-leaf-data');
  const firstProof = await assertOk('get proof for tamper test', requestJson(
    `/api/elections/${encodeURIComponent(ELECTION_ID)}/proof/${nullifiers[0]}`,
  ));
  const fakeRoot = computeLocalRoot(fakeLeafHash, firstProof.proof);
  if (fakeRoot !== chainRoot) {
    console.log('[OK] tampered leafHash produces different root (expected)');
  } else {
    throw new Error('Tampered leafHash should NOT produce matching root');
  }

  // 9. tally 조회 + 검증
  const tally = await assertOk('get tally', requestJson(`/api/elections/${encodeURIComponent(ELECTION_ID)}/tally`));
  console.log(`[INFO] tally: ${JSON.stringify(tally.results)}, total=${tally.totalVotes}`);

  // 더미 투표가 포함되므로 totalVotes >= 실제 투표 수
  if (tally.totalVotes < voters.length) {
    throw new Error(`Tally totalVotes too low: expected>=${voters.length}, got=${tally.totalVotes}`);
  }
  // 각 후보에 최소 1표 이상 (실제 투표분)
  if (!tally.results['CANDIDATE_A'] || tally.results['CANDIDATE_A'] < 1) {
    throw new Error(`CANDIDATE_A should have >= 1 vote, got ${tally.results['CANDIDATE_A']}`);
  }
  if (!tally.results['CANDIDATE_B'] || tally.results['CANDIDATE_B'] < 1) {
    throw new Error(`CANDIDATE_B should have >= 1 vote, got ${tally.results['CANDIDATE_B']}`);
  }
  console.log(`[OK] tally results valid (includes ${tally.totalVotes - voters.length} dummy votes)`);

  console.log('[DONE] Merkle + Tally E2E smoke test completed');
}

main().catch((err) => {
  console.error(`[FAIL] ${err.message}`);
  process.exit(1);
});
